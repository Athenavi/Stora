-- Zero-knowledge (E2EE) private spaces.
--
-- The server stores only public KDF parameters and ciphertext: it has no key
-- material and no code path that decrypts anything here. See docs/design-e2ee.md
-- for the key hierarchy and ciphertext format.
--
-- This is deliberately separate from `vaults`/`vault_items`, which are
-- *server-side* encrypted (decryptable, searchable, thumbnailable). The two have
-- different security promises and must not be conflated in the UI or the schema.

create table if not exists e2ee_vaults
(
    id                   bigint generated by default as identity
        primary key,
    user_id              bigint      not null
        references users
            on delete cascade,
    name                 text        not null, -- 明文标签，仅用于在界面上区分多个保险库
    kdf_salt             text        not null, -- base64，客户端生成
    kdf_iterations       integer     not null, -- 客户端生成，服务端只回传
    wrapped_key          text        not null, -- base64(AES-GCM(masterKey, vaultKey))
    recovery_wrapped_key text,                 -- base64(AES-GCM(recoveryKey, vaultKey))
    created_at           timestamp   not null default now(),
    updated_at           timestamp   not null default now()
);

create index if not exists idx_e2ee_vaults_user_id
    on e2ee_vaults (user_id);

create table if not exists e2ee_items
(
    id           bigint generated by default as identity
        primary key,
    vault_id     bigint      not null
        references e2ee_vaults
            on delete cascade,
    user_id      bigint      not null
        references users
            on delete cascade,
    enc_name     text        not null, -- 密文文件名；服务端不可读，也不得记入日志
    enc_meta     text,                 -- 密文元数据 JSON（原始大小/MIME/时间）
    storage_path text        not null, -- 密文对象在存储层的键
    size_cipher  bigint      not null default 0, -- 密文长度，服务端可见
    created_at   timestamp   not null default now(),
    updated_at   timestamp   not null default now()
);

create index if not exists idx_e2ee_items_vault_id
    on e2ee_items (vault_id);

create index if not exists idx_e2ee_items_user_id
    on e2ee_items (user_id);

-- DOWNGRADE
drop index if exists idx_e2ee_items_user_id;
drop index if exists idx_e2ee_items_vault_id;
drop table if exists e2ee_items;
drop index if exists idx_e2ee_vaults_user_id;
drop table if exists e2ee_vaults;
