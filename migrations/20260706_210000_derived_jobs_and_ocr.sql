-- UPGRADE
-- 1. Generalise the thumbnail job queue into a derived-state queue.
--
-- Thumbnails and OCR are the same shape of work — asynchronous, per file,
-- retryable — and the thumbnail worker already existed as the first copy of this
-- pattern. A second table with a third copy of the same worker SQL would be a
-- maintenance liability, so both kinds now share one queue and one worker.

create table if not exists derived_jobs
(
    id         bigint generated by default as identity
        primary key,
    file_id    bigint      not null
        references file_items
            on delete cascade,
    kind       varchar(16) not null, -- thumbnail | ocr
    status     varchar(16) not null default 'pending', -- pending | running | done | failed
    attempts   integer     not null default 0,
    last_error text,
    created_at timestamp   not null default now(),
    updated_at timestamp   not null default now(),
    unique (file_id, kind)
);

create index if not exists idx_derived_jobs_status_kind
    on derived_jobs (status, kind, id);

-- thumbnail_jobs only ever held thumbnail jobs. They are re-derivable from the
-- stored objects, so the rows are deliberately not migrated.
drop table if exists thumbnail_jobs;

-- 2. Text extracted from images. Read by the search index builder, which is why
--    it sits next to the file rather than in a separate search document.
create table if not exists ocr_texts
(
    file_id    bigint primary key
        references file_items
            on delete cascade,
    content    text      not null,
    engine     varchar(32) not null default 'tesseract',
    created_at timestamp not null default now()
);

-- DOWNGRADE
drop table if exists ocr_texts;
drop index if exists idx_derived_jobs_status_kind;
drop table if exists derived_jobs;
-- thumbnail_jobs is intentionally not recreated: derived_jobs supersedes it and
-- its contents are regenerable by re-enqueueing.
