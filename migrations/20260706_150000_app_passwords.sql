-- Application-specific passwords for protocols that only speak HTTP Basic auth
-- (WebDAV clients: macOS Finder, Windows Explorer, rclone).
--
-- The account password must not be used there: those clients store credentials
-- in plain text on disk, and a leaked one could not be revoked without changing
-- the account password everywhere.

create table if not exists app_passwords
(
    id            bigint generated by default as identity
        primary key,
    user_id       bigint       not null
        references users
            on delete cascade,
    name          varchar(100) not null,
    password_hash varchar(128) not null,
    last_used_at  timestamp,
    created_at    timestamp    not null default now()
);

create index if not exists idx_app_passwords_user_id
    on app_passwords (user_id);

-- DOWNGRADE
drop index if exists idx_app_passwords_user_id;
drop table if exists app_passwords;
