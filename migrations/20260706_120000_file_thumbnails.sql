-- Thumbnails are generated asynchronously after an upload lands, so an upload
-- never waits on image decoding or ffmpeg.

create table if not exists file_thumbnails
(
    id           bigint generated by default as identity
        primary key,
    file_id      bigint      not null
        references file_items
            on delete cascade,
    size         varchar(8)  not null, -- sm | md | lg
    width        integer     not null,
    height       integer     not null,
    storage_path text        not null, -- content-addressed key returned by StoreHash
    created_at   timestamp   not null default now(),
    unique (file_id, size)
);

create index if not exists idx_file_thumbnails_file_id
    on file_thumbnails (file_id);

-- One row per file: re-uploading a file resets the row instead of queueing a duplicate.
create table if not exists thumbnail_jobs
(
    id         bigint generated by default as identity
        primary key,
    file_id    bigint      not null
        references file_items
            on delete cascade,
    status     varchar(16) not null default 'pending', -- pending | running | done | failed
    attempts   integer     not null default 0,
    last_error text,
    created_at timestamp   not null default now(),
    updated_at timestamp   not null default now(),
    unique (file_id)
);

create index if not exists idx_thumbnail_jobs_status
    on thumbnail_jobs (status, id);

-- DOWNGRADE
drop table if exists thumbnail_jobs;
drop index if exists idx_file_thumbnails_file_id;
drop table if exists file_thumbnails;
