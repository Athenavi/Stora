-- 3. The handlers rely on "ON CONFLICT DO NOTHING" for these pairs to keep them
--    unique, which silently does nothing without a unique constraint. Drop any
--    pre-existing duplicates (keeping the oldest row) before adding the indexes.

delete from team_members a
 using team_members b
 where a.id > b.id
   and a.team_id = b.team_id
   and a.user_id = b.user_id;

create unique index if not exists uq_team_members_team_id_user_id
    on team_members (team_id, user_id);

delete from file_tag_assignments a
 using file_tag_assignments b
 where a.id > b.id
   and a.file_id = b.file_id
   and a.tag_id = b.tag_id;

