create table if not exists upload_sessions
(
    id             bigint generated by default as identity
        primary key,
    session_id     varchar(64)  not null,
    user_id        bigint       not null
        references users
            on delete cascade,
    filename       varchar(255) not null,
    file_path      text         not null,
    file_size      bigint       not null default 0,
    received_bytes bigint       not null default 0,
    status         varchar(20)  not null default 'active',
    created_at     timestamp    not null default now(),
    updated_at     timestamp    not null default now()
);

create unique index if not exists uq_upload_sessions_session_id
    on upload_sessions (session_id);

create table if not exists transcode_tasks
(
    id            bigint generated by default as identity
        primary key,
    file_id       bigint      not null
        references file_items
            on delete cascade,
    user_id       bigint      not null
        references users
            on delete cascade,
    status        varchar(20) not null default 'pending',
    target_format varchar(20),
    output_path   text,
    progress      integer     not null default 0,
    error_msg     text,
    created_at    timestamp   not null default now(),
    updated_at    timestamp   not null default now()
);

create index if not exists idx_transcode_tasks_user_id_file_id
    on transcode_tasks (user_id, file_id);

